# промпты для нейросетки

# для анализа просим вернуть строго json, иначе потом тяжело парсить
ANALYZE_SYSTEM_PROMPT = (
    "Ты помощник для студентов, который анализирует учебные конспекты. "
    "Отвечай только валидным JSON, без markdown и без лишнего текста до или после."
)


def build_analyze_prompt(note_text):
    prompt = (
        "Проанализируй конспект ниже и верни JSON с полями:\n"
        "- subject: предмет/дисциплина (короткая строка)\n"
        "- summary: общее резюме на 2-5 предложений\n"
        "- topics: массив объектов {\"title\": ..., \"content\": ...}\n"
        "- questions: массив строк, вопросы для самопроверки (5-8 штук)\n\n"
        "Отвечай на языке конспекта.\n\n"
        "=== КОНСПЕКТ ===\n"
        + note_text +
        "\n=== КОНЕЦ ===\n\n"
        "Верни только JSON."
    )
    return prompt


QA_SYSTEM_PROMPT = (
    "Ты помощник для студентов. Отвечай на вопрос только по тексту конспекта. "
    "Если в тексте нет ответа - так и скажи. Отвечай кратко, на языке вопроса."
)


def build_qa_prompt(note_text, question):
    return (
        "=== ТЕКСТ КОНСПЕКТА ===\n"
        + note_text +
        "\n=== КОНЕЦ ===\n\n"
        "Вопрос: " + question + "\n\n"
        "Ответь опираясь на текст выше."
    )
